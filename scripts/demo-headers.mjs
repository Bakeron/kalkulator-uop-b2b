// Headers of the website demo (Cloudflare Pages reads `_headers` from the build output).
// One place for the vite plugin (vite.config.ts writes the file), for the block in the home page's
// `_headers` (scripts/demo-na-strone.mjs) and for the tests, because a wrong header means a white page.

/** Folder of the demo on the home page: szymonbakonis.pl/kalkulator-uop-b2b/. */
export const DEMO_DIR = "kalkulator-uop-b2b";

/** Pages allowed to show the demo in a frame - the author's home page only. */
export const FRAME_ANCESTORS = ["'self'", "https://szymonbakonis.pl", "https://szymonbakonis.pages.dev"];

/** Public APIs the demo may call: NBP exchange rates, Sejm acts, the rates file in the repository. */
export const CONNECT_SRC = ["'self'", "https://api.nbp.pl", "https://api.sejm.gov.pl", "https://raw.githubusercontent.com"];

/** Content-Security-Policy of the demo - the same limits as the desktop app (tauri.conf.json), plus the frame rule. */
export function demoCsp() {
  return [
    "default-src 'self'",
    "script-src 'self'",
    // Vite emits CSS files; React sets style attributes through the DOM, which CSP does not block.
    "style-src 'self'",
    "font-src 'self'",
    "img-src 'self' data:",
    `connect-src ${CONNECT_SRC.join(" ")}`,
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    `frame-ancestors ${FRAME_ANCESTORS.join(" ")}`,
  ].join("; ");
}

/** The `_headers` file. Never X-Frame-Options: DENY - the demo lives in a frame. */
export function demoHeaders() {
  return [
    "/*",
    `  Content-Security-Policy: ${demoCsp()}`,
    "  X-Robots-Tag: noindex",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: no-referrer",
    "",
  ].join("\n");
}

/** Lines that fence the demo's block in the home page's `_headers` (the script replaces what is between). */
export const HOME_BLOCK_START = `# >>> ${DEMO_DIR} - generated by kalkulator-uop-b2b/scripts/demo-na-strone.mjs, do not edit by hand`;
export const HOME_BLOCK_END = `# <<< ${DEMO_DIR}`;

/**
 * The demo's block in the home page's `_headers`. Cloudflare applies every matching rule in file order,
 * so the home page's own CSP (no NBP/Sejm APIs) and X-Frame-Options: DENY from "/*" are detached ("!")
 * first, then the demo's are set. noindex and nosniff come from "/*" already.
 */
export function homeHeadersBlock() {
  return [
    HOME_BLOCK_START,
    `/${DEMO_DIR}/*`,
    "  ! Content-Security-Policy",
    "  ! X-Frame-Options",
    "  ! Referrer-Policy",
    `  Content-Security-Policy: ${demoCsp()}`,
    "  Referrer-Policy: no-referrer",
    HOME_BLOCK_END,
  ].join("\n");
}

/** The home page's `_headers` with the demo's block put in (at the end) or replaced. */
export function withHomeBlock(headers) {
  const start = headers.indexOf(HOME_BLOCK_START);
  const end = headers.indexOf(HOME_BLOCK_END);
  if (start !== -1 && end > start) {
    return headers.slice(0, start) + homeHeadersBlock() + headers.slice(end + HOME_BLOCK_END.length);
  }
  if (start !== -1 || end !== -1) throw new Error("_headers strony: uszkodzony blok dema (jest tylko jedna z linii granicznych)");
  return `${headers.replace(/\s*$/, "")}\n\n${homeHeadersBlock()}\n`;
}
